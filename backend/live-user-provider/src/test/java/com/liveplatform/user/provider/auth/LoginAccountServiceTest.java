package com.liveplatform.user.provider.auth;

import com.liveplatform.user.api.UserBusinessException;
import com.liveplatform.user.provider.cache.UserCacheLoader;
import com.liveplatform.user.provider.dao.UserPhoneRepository;
import com.liveplatform.user.provider.dao.UserRepository;
import com.liveplatform.user.provider.service.UserService;
import org.junit.jupiter.api.*;
import org.springframework.context.ApplicationEventPublisher;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.*;
import java.util.concurrent.*;
import java.util.concurrent.atomic.AtomicInteger;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

class LoginAccountServiceTest {
    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private UserPhoneRepository phones;
    private UserCacheLoader cache;
    private LoginAccountService accounts;

    @BeforeEach
    void setUp() {
        database = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("""
                CREATE TABLE t_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nickname VARCHAR(32), avatar_url VARCHAR(512), status INT, version BIGINT,
                created_at TIMESTAMP, updated_at TIMESTAMP)
                """);
        jdbc.execute("""
                CREATE TABLE t_user_phone (phone VARCHAR(11) PRIMARY KEY, user_id BIGINT UNIQUE
                REFERENCES t_user(id), created_at TIMESTAMP)
                """);
        phones = spy(new UserPhoneRepository(jdbc));
        cache = mock(UserCacheLoader.class);
        var users = new UserService(new UserRepository(jdbc), cache, mock(ApplicationEventPublisher.class));
        accounts = new LoginAccountService(phones, users, new DataSourceTransactionManager(database));
    }

    @AfterEach
    void tearDown() { database.shutdown(); }

    @Test
    void repeatedLoginReusesUserAndDisabledStatusBypassesCache() {
        var first = accounts.findOrRegister("13800138000");
        assertThat(accounts.findOrRegister("13800138000").getId()).isEqualTo(first.getId());
        jdbc.update("UPDATE t_user SET status = 0 WHERE id = ?", first.getId());
        assertThatThrownBy(() -> accounts.findOrRegister("13800138000"))
                .isInstanceOfSatisfying(UserBusinessException.class,
                        e -> assertThat(e.getCode()).isEqualTo("USER_DISABLED"));
        assertThatThrownBy(() -> accounts.getActiveUser(first.getId())).isInstanceOf(UserBusinessException.class);
        verifyNoInteractions(cache);
    }

    @Test
    void failedPhoneInsertRollsBackNewUser() {
        doThrow(new IllegalStateException("insert failed")).when(phones).insert(anyString(), anyLong(), any());
        assertThatThrownBy(() -> accounts.findOrRegister("13800138000")).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM t_user", Integer.class)).isZero();
    }

    @Test
    void concurrentFirstLoginsReturnSameUserAndLeaveNoOrphan() throws Exception {
        var barrier = new CyclicBarrier(2);
        var reads = new AtomicInteger();
        doAnswer(invocation -> {
            Object result = invocation.callRealMethod();
            if (reads.incrementAndGet() <= 2) { barrier.await(5, TimeUnit.SECONDS); }
            return result;
        }).when(phones).findUserId("13800138000");
        var pool = Executors.newFixedThreadPool(2);
        try {
            var a = pool.submit(() -> accounts.findOrRegister("13800138000"));
            var b = pool.submit(() -> accounts.findOrRegister("13800138000"));
            assertThat(a.get(10, TimeUnit.SECONDS).getId()).isEqualTo(b.get(10, TimeUnit.SECONDS).getId());
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM t_user", Integer.class)).isEqualTo(1);
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM t_user_phone", Integer.class)).isEqualTo(1);
        } finally { pool.shutdownNow(); }
    }
}
